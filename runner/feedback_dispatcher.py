#!/usr/bin/env python3
"""Event feedback dispatcher (Phase 4.3).

Turns events the detect-only poller marked feedback-eligible into hybrid
(ROUTINE / SIGNIFICANT) coaching feedback, generated by Claude under
workflows/event-feedback.md and delivered through Telegram via an idempotent
outbox in the event store (schema v2):

    select eligible events -> group -> queue (quiet hours) -> revalidate
    -> auth preflight + budget -> generate (Claude) -> revalidate -> deliver
    (Telegram) -> record outcome

It is a separate program from the poller: the poller never imports this
module and never gains Claude or Telegram credentials.

Specification: runner/feedback-dispatcher.md.

Usage:
    python3 runner/feedback_dispatcher.py --simulate [--at ISO] [--until ISO]
    python3 runner/feedback_dispatcher.py --status
    python3 runner/feedback_dispatcher.py --migrate-check
    python3 runner/feedback_dispatcher.py --migrate          # applies schema v2 (with backup)
    python3 runner/feedback_dispatcher.py --once             # live; requires FEEDBACK_DISPATCH_ENABLED=true
    python3 runner/feedback_dispatcher.py --simulate --max-batches 1              # prints a plan token
    python3 runner/feedback_dispatcher.py --once --expect-plan TOKEN --max-batches 1   # supervised run
    python3 runner/feedback_dispatcher.py --requeue-failed-delivery   # only definitive Telegram failures
    python3 runner/feedback_dispatcher.py --downgrade-v1     # rollback; keeps all detections
"""

