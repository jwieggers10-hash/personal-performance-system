# --------------------------------------------------------------------------
# Policy constants (see runner/feedback-dispatcher.md)
# --------------------------------------------------------------------------

DEFAULT_DAILY_CLAUDE_BUDGET = 6
MAX_GENERATION_ATTEMPTS = 3
GENERATION_BACKOFF = (timedelta(minutes=15), timedelta(minutes=60))
MAX_DELIVERY_ATTEMPTS = 4
DELIVERY_BACKOFF = (timedelta(minutes=5), timedelta(minutes=15), timedelta(minutes=60))
MAX_RETRY_AFTER = timedelta(hours=1)
# A generated message not delivered within this window is expired rather
# than sent late.
DELIVERY_MAX_AGE = timedelta(hours=12)
# A batch left 'processing' this long belongs to a dead dispatcher.
PROCESSING_LEASE = timedelta(minutes=45)
MAX_GENERATIONS_PER_RUN = 3
# Failure categories where Telegram confirmed the message was not delivered,
# so an operator may requeue them (--requeue-failed-delivery) without risk
# of a duplicate. delivery_outcome_unknown is deliberately absent.
RETRY_SAFE_DELIVERY_FAILURES = ("telegram_rejected", "telegram_retries_exhausted")
LOCK_STALE_SECONDS = 3600
SIMULATION_STEP = timedelta(minutes=15)
SIMULATION_MAX_SPAN = timedelta(days=7)

# Fixed, content-free system alert texts. Urgency 'urgent' bypasses quiet hours.
SYSTEM_ALERTS = {
    "claude_auth_escalation": ("urgent", "[URGENT] Coaching system: Claude authentication has failed repeatedly. "
                               "Training feedback is paused and the 07:00 Daily Review will fail until the coach "
                               "account is re-authenticated on the server."),
    "claude_auth_expiry": ("attention", "[ATTENTION] Coaching system: the Claude login on the server expires within "
                           "7 days. Re-authenticate the coach account to avoid an outage."),
    "claude_budget_exhausted": ("attention", "[ATTENTION] Coaching system: today's Claude call budget for training "
                                "feedback is used up. Remaining feedback is deferred and may expire."),
}

LEVEL_HEADERS = {
    ("event", "routine"): "Training feedback",
    ("event", "significant"): "Training feedback (detailed)",
    ("morning_digest", "routine"): "Morning training feedback",
    ("morning_digest", "significant"): "Morning training feedback (detailed)",
}

UTC = dt_timezone.utc


@dataclass
class Settings:
    repo_root: Path
    tz: ZoneInfo
    daily_budget: int = DEFAULT_DAILY_CLAUDE_BUDGET
    apple_health_verified: bool = False
    claude_binary: str = wr.DEFAULT_CLAUDE_BINARY
    # Returns one of feedback_claude.AUTH_*; defaults to `claude auth status`.
    auth_status: Optional[Callable[[], str]] = None
    auth_expires_on: Optional[date] = None
    max_generations_per_run: int = MAX_GENERATIONS_PER_RUN


# --------------------------------------------------------------------------
# Daily Review coordination (read-only file checks)
# --------------------------------------------------------------------------

def daily_review_running(repo_root: Path) -> bool:
    lock_dir = repo_root / "runtime" / "locks"
    return lock_dir.is_dir() and any(lock_dir.glob("daily-review-*.lock"))


def daily_review_settled(repo_root: Path, local_date: date) -> bool:
    review = repo_root / "reviews" / "daily" / f"{local_date.isoformat()}.md"
    return review.exists() and not daily_review_running(repo_root)


