def open_simulation_store(db_path: Path, now: datetime) -> fs.FeedbackStore:
    """In-memory copy of the production store (opened read-only), migrated to
    v2 in memory. Nothing can reach the file on disk."""
    store = es.EventStore.open_snapshot(db_path)
    fs.migrate_to_v2(store.conn, now_text=fp.iso_utc(now))
    return fs.FeedbackStore(store)


def batch_overview(store: fs.FeedbackStore, tz: ZoneInfo) -> list:
    """Per-batch aggregates for the simulation report: no identifiers, no
    message text, no activity times."""
    rows = []
    for batch in store.conn.execute("SELECT * FROM feedback_batches ORDER BY id"):
        items = store.conn.execute(
            "SELECT e.source AS source, COUNT(*) AS n FROM feedback_items f JOIN events e ON e.id = f.event_id "
            "WHERE f.batch_id = ? GROUP BY 1", (batch["id"],)).fetchall()
        release = fp.parse_iso(batch["release_at"])
        rows.append({
            "kind": batch["kind"], "urgency": batch["urgency"], "level": batch["level"], "state": batch["state"],
            "stage": batch["stage"], "events_by_source": {r["source"]: r["n"] for r in items},
            "release_local": release.astimezone(tz).strftime("%Y-%m-%d %H:%M %Z") if release else None,
            "generation_attempts": batch["generation_attempts"], "delivery_attempts": batch["delivery_attempts"],
            "error_category": batch["error_category"],
        })
    return rows


def simulate(db_path: Path, settings: Settings, *, start: datetime, until: Optional[datetime],
             log: Callable[..., None]) -> dict:
    store = open_simulation_store(db_path, start)
    # Not even `claude auth status` runs in simulation.
    settings = replace(settings, auth_status=lambda: fc.AUTH_NOT_CHECKED)
    gateway = fc.SimulatedGateway()
    transport = RecordingTransport()
    dispatcher = Dispatcher(store, settings, gateway=gateway, telegram=SIMULATED_TELEGRAM, http_post=transport,
                            log=log, owner="simulation")
    ineligible = store.ineligible_event_counts()
    dispatcher.activate(start)
    activation_counts = dict(dispatcher.counts)
    ticks, totals, moment = 0, {}, start
    end = until or start
    if end - start > SIMULATION_MAX_SPAN:
        raise ValueError("simulation span is limited to 7 days")
    while True:
        counts = dispatcher.run(moment)
        ticks += 1
        for name, value in counts.items():
            totals[name] = totals.get(name, 0) + value
        if moment + SIMULATION_STEP > end:
            break
        moment += SIMULATION_STEP
    try:
        return {
            "mode": "simulate",
            "simulated_from": fp.iso_utc(start),
            "simulated_until": fp.iso_utc(moment),
            "ticks": ticks,
            "activation": activation_counts or {"already_activated": 1},
            "events_not_feedback_eligible_by_status": ineligible,
            "totals": dict(sorted(totals.items())),
            "batches": batch_overview(store, settings.tz),
            "claude_invocations": 0,
            "simulated_claude_calls": gateway.calls,
            "telegram_requests": 0,
            "simulated_telegram_messages": len(transport.messages),
            "daily_claude_budget": settings.daily_budget,
            "status": store.status_summary(moment.astimezone(settings.tz).date().isoformat()),
        }
    finally:
        store.store.close()


