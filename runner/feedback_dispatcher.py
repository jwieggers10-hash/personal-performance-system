# --------------------------------------------------------------------------
# Dispatcher
# --------------------------------------------------------------------------

class Dispatcher:
    def __init__(self, store: fs.FeedbackStore, settings: Settings, *, gateway, telegram: Optional[td.TelegramConfig],
                 http_post: Optional[Callable] = None, log: Optional[Callable[..., None]] = None,
                 owner: Optional[str] = None,
                 review_settled: Optional[Callable[[date], bool]] = None,
                 review_running: Optional[Callable[[], bool]] = None):
        self.store = store
        self.settings = settings
        self.gateway = gateway
        self.telegram = telegram
        self.http_post = http_post
        self.log = log or (lambda **fields: None)
        self.owner = owner or uuid.uuid4().hex
        self.review_settled = review_settled or (lambda d: daily_review_settled(settings.repo_root, d))
        self.review_running = review_running or (lambda: daily_review_running(settings.repo_root))
        self.auth_status = settings.auth_status or (
            lambda: fc.cli_auth_status(settings.claude_binary, cwd=settings.repo_root))
        self.counts: dict = {}
        self._preflight: Optional[fc.Preflight] = None
        self._claude_blocked: Optional[str] = None

    # -- helpers ----------------------------------------------------------

    def bump(self, name: str, n: int = 1) -> None:
        self.counts[name] = self.counts.get(name, 0) + n

    def local_date(self, now: datetime) -> date:
        return now.astimezone(self.settings.tz).date()

    def activated_at(self) -> Optional[datetime]:
        return fp.parse_iso(self.store.get_meta("feedback_activated_at"))

    def activate(self, now: datetime) -> None:
        """Records the first activation once; events older than 24 h at that
        moment are expired instead of receiving late feedback."""
        with self.store.transaction():
            if self.store.get_meta("feedback_activated_at") is None:
                self.store.set_meta("feedback_activated_at", fp.iso_utc(now))
                self.bump("activated")

    # -- run --------------------------------------------------------------

    def run(self, now: datetime) -> dict:
        self.counts = {}
        self._preflight = None
        self._claude_blocked = None
        self.recover_stale(now)
        self.intake(now)
        self.check_auth_expiry(now)
        self.process_due(now)
        return dict(sorted(self.counts.items()))

    def recover_stale(self, now: datetime) -> None:
        now_text = fp.iso_utc(now)
        with self.store.transaction():
            for batch in self.store.stale_processing_batches(fp.iso_utc(now - PROCESSING_LEASE)):
                if batch["stage"] == "generate":
                    # Generation has no external side effect: safe to retry.
                    self.store.requeue_batch(batch["id"], now_text)
                    self.bump("recovered_generation")
                elif batch["parts_total"] and batch["parts_sent"] >= batch["parts_total"]:
                    # Every part was confirmed by Telegram before the crash.
                    self.store.finish_batch(batch["id"], "delivered", now_text)
                    self.bump("recovered_delivered")
                elif batch["inflight_part"] is None:
                    # No sendMessage was in flight: nothing can have reached
                    # Telegram beyond the confirmed parts, so resuming is safe.
                    self.store.requeue_batch(batch["id"], now_text)
                    self.bump("recovered_delivery")
                else:
                    # A send was in flight and may or may not have reached
                    # Telegram. At-most-once: never resend; record it.
                    self.store.finish_batch(batch["id"], "failed", now_text,
                                            error_category="delivery_outcome_unknown",
                                            item_reason="delivery_outcome_unknown")
                    self.bump("failed_delivery_outcome_unknown")

    # -- intake -----------------------------------------------------------

    def intake(self, now: datetime) -> None:
        now_text = fp.iso_utc(now)
        activated_at = self.activated_at()
        with self.store.transaction():
            eligible = []
            for event in self.store.candidate_events():
                self.bump("candidates")
                verdict = fp.assess_event(event, now=now, activated_at=activated_at,
                                          apple_health_verified=self.settings.apple_health_verified)
                if verdict.decision == "wait":
                    self.bump("waiting_to_settle")
                elif verdict.decision == "eligible":
                    eligible.append(event)
                elif self.store.create_item(event["id"], state=verdict.decision, reason=verdict.reason,
                                            now_text=now_text):
                    self.bump(f"items_{verdict.decision}_{verdict.reason}")
            for group in fp.group_events(eligible):
                self._queue_group(group, now)

    def _queue_group(self, group: list, now: datetime) -> None:
        now_text = fp.iso_utc(now)
        tz = self.settings.tz
        level, _ = self._level_for(group)
        today = self.local_date(now)
        batch_id = None
        if fp.in_quiet_hours(now, tz):
            release = fp.next_release(now, tz)
            batch_id = self._digest_batch(release.astimezone(tz).date(), release, now_text)
            if batch_id is not None:
                self.bump("items_queued_for_morning", len(group))
        else:
            open_digest = self.store.get_batch_by_key(f"digest:{today.isoformat()}")
            if open_digest is not None and open_digest["state"] == "queued" and open_digest["stage"] == "generate":
                batch_id = open_digest["id"]
                self.bump("items_joined_morning_digest", len(group))
        if batch_id is None:
            key = "event:" + ",".join(str(e["id"]) for e in sorted(group, key=lambda e: e["id"]))
            batch_id = self.store.create_batch(batch_key=key, kind="event", release_at=now_text, now_text=now_text,
                                               local_date=today.isoformat(), level=level)
            if batch_id is None:
                batch_id = self.store.get_batch_by_key(key)["id"]
            else:
                self.bump("batches_created_event")
        for event in group:
            if self.store.create_item(event["id"], state="queued", batch_id=batch_id, level=level, now_text=now_text):
                self.bump("items_queued")
                self.bump(f"items_level_{level}")
            else:
                self.bump("items_already_present")

    def _digest_batch(self, release_date: date, release: datetime, now_text: str) -> Optional[int]:
        key = f"digest:{release_date.isoformat()}"
        existing = self.store.get_batch_by_key(key)
        if existing is not None:
            joinable = existing["state"] == "queued" and existing["stage"] == "generate"
            return existing["id"] if joinable else None
        self.bump("batches_created_morning_digest")
        return self.store.create_batch(batch_key=key, kind="morning_digest", release_at=fp.iso_utc(release),
                                       now_text=now_text, local_date=release_date.isoformat())

    def _level_for(self, events: list) -> "tuple[str, list]":
        times = [fp.event_time(e) for e in events if e["source"] in fp.TRAINING_SOURCES and fp.event_time(e)]
        if not times:
            return "routine", []
        first = min(times)
        ids = {e["id"] for e in events}
        before = [r for r in self.store.training_events_between(fp.iso_utc(first - fp.RETURN_AFTER_GAP),
                                                                fp.iso_utc(first))
                  if r["id"] not in ids]
        previous = max((fp.parse_iso(r["start_time_utc"]) for r in before), default=None)
        baselines = [fp.parse_iso(self.store.baseline_completed_at(s)) for s in fp.TRAINING_SOURCES]
        covers = all(b is not None and b <= first - fp.RETURN_AFTER_GAP for b in baselines)
        return fp.classify_level(events, previous_training_start=previous, history_covers_gap=covers)

    # -- system alerts ----------------------------------------------------

    def enqueue_alert(self, token: str, now: datetime) -> None:
        urgency, text = SYSTEM_ALERTS[token]
        local_date = self.local_date(now).isoformat()
        release = now if urgency == "urgent" else fp.next_release(now, self.settings.tz)
        now_text = fp.iso_utc(now)
        with self.store.transaction():
            created = self.store.create_batch(batch_key=f"alert:{token}:{local_date}", kind="system_alert",
                                              release_at=fp.iso_utc(release), now_text=now_text,
                                              local_date=local_date, urgency=urgency, stage="deliver",
                                              message_text=text)
        if created:
            self.bump(f"alert_enqueued_{token}")
            self.log(event="system_alert_enqueued", alert=token, urgency=urgency)

    def check_auth_expiry(self, now: datetime) -> None:
        """Date-only check; runs every tick without touching the CLI."""
        if fc.auth_expiry_approaching(self.settings.auth_expires_on, self.local_date(now)):
            self.enqueue_alert("claude_auth_expiry", now)

    def preflight(self, now: datetime) -> fc.Preflight:
        """At most once per run, and only when a generation is about to call
        Claude. A CLI that reports itself logged out counts as an auth
        failure towards escalation."""
        if self._preflight is None:
            self._preflight = fc.auth_preflight(
                claude_binary=self.settings.claude_binary, auth_status=self.auth_status,
                now=now, consecutive_failures=int(self.store.get_meta("dispatcher.auth_consecutive_failures") or 0),
                escalated_at=fp.parse_iso(self.store.get_meta("dispatcher.auth_escalated_at")),
                auth_expires_on=self.settings.auth_expires_on, local_today=self.local_date(now),
            )
            self.log(event="auth_preflight", ok=self._preflight.ok, reason=self._preflight.reason,
                     assurance=self._preflight.assurance)
            if self._preflight.reason == "cli_logged_out":
                self._record_auth_result(False, now)
        return self._preflight

    def _record_auth_result(self, ok: bool, now: datetime) -> None:
        with self.store.transaction():
            if ok:
                self.store.set_meta("dispatcher.auth_consecutive_failures", "0")
                self.store.set_meta("dispatcher.auth_escalated_at", None)
                return
            failures = int(self.store.get_meta("dispatcher.auth_consecutive_failures") or 0) + 1
            self.store.set_meta("dispatcher.auth_consecutive_failures", str(failures))
            escalate = failures >= fc.AUTH_ESCALATION_THRESHOLD
            if escalate:
                self.store.set_meta("dispatcher.auth_escalated_at", fp.iso_utc(now))
        if escalate:
            self.bump("auth_escalated")
            self.enqueue_alert("claude_auth_escalation", now)

    # -- processing -------------------------------------------------------

    def process_due(self, now: datetime) -> None:
        """Generation pass, then a delivery pass, so feedback generated in
        this run is delivered in this run too."""
        generations = 0
        for stage in fs.BATCH_STAGES:
            for batch in self.store.due_batches(fp.iso_utc(now)):
                if batch["stage"] != stage:
                    continue
                if not fp.may_process(batch["urgency"], now, self.settings.tz, self.review_settled):
                    self.bump(f"deferred_quiet_or_morning_gate_{stage}")
                    continue
                if stage == "deliver":
                    self.deliver(batch["id"], now)
                elif generations >= self.settings.max_generations_per_run:
                    self.bump("deferred_run_limit")
                else:
                    generations += 1
                    self.generate(batch["id"], now)

    def _revalidate_items(self, batch_id: int, now: datetime) -> "tuple[list, list]":
        """Marks items that are no longer eligible; returns (valid rows,
        verdict decisions of the removed ones)."""
        now_text = fp.iso_utc(now)
        valid, removed = [], []
        for row in self.store.batch_items(batch_id):
            verdict = fp.revalidate(row, now=now, apple_health_verified=self.settings.apple_health_verified)
            if verdict.decision == "eligible":
                valid.append(row)
            else:
                self.store.set_item_state(row["item_id"], verdict.decision, now_text, reason=verdict.reason)
                removed.append(verdict.decision)
                self.bump(f"revalidation_{verdict.decision}_{verdict.reason}")
        return valid, removed

    def _finish_empty(self, batch_id: int, removed: list, now_text: str) -> None:
        state = "suppressed" if "suppressed" in removed else "expired"
        self.store.finish_batch(batch_id, state, now_text, error_category="no_eligible_events")
        self.bump(f"batches_{state}")

    def _claude_unavailable(self, now: datetime) -> Optional[str]:
        if self._claude_blocked:
            return self._claude_blocked
        if self.review_running():
            return "daily_review_running"
        preflight = self.preflight(now)
        if not preflight.ok:
            return preflight.reason
        return None

    def generate(self, batch_id: int, now: datetime) -> None:
        now_text = fp.iso_utc(now)
        blocked = self._claude_unavailable(now)
        if blocked:
            self.bump(f"deferred_{blocked}")
            return
        local_date = self.local_date(now)
        if self.store.claude_calls_on(local_date.isoformat()) >= self.settings.daily_budget:
            self.bump("deferred_budget_exhausted")
            self.enqueue_alert("claude_budget_exhausted", now)
            return

        with self.store.transaction():
            if not self.store.claim_batch(batch_id, stage="generate", owner=self.owner, now_text=now_text):
                self.bump("claim_lost")
                return
            valid, removed = self._revalidate_items(batch_id, now)
            if not valid:
                self._finish_empty(batch_id, removed, now_text)
                return
        batch = self.store.get_batch(batch_id)
        level, reasons = self._level_for(valid)
        batch_ref = f"B{batch_id}"
        refs = fc.event_refs(valid)
        prompt = fc.build_prompt(repo_root=self.settings.repo_root, batch_ref=batch_ref, level=level,
                                 level_reasons=reasons, kind=batch["kind"], events=valid, local_date=local_date,
                                 athlete_timezone=str(self.settings.tz))
        schema = fc.output_schema(level)

        attempt_prompt, outcome, feedback = prompt, None, None
        for call_number in range(1, fc.MAX_CALLS_PER_GENERATION + 1):
            if call_number > 1 and self.store.claude_calls_on(local_date.isoformat()) >= self.settings.daily_budget:
                break
            with self.store.transaction():
                call_id = self.store.record_claude_call(batch_id=batch_id, local_date=local_date.isoformat(),
                                                        started_at=fp.iso_utc(now))
            self.bump("claude_calls")
            result = self.gateway.call(attempt_prompt, schema)
            outcome = result.outcome
            if outcome == fc.OUTCOME_OK:
                feedback, problems = fc.validate_feedback(result.structured, batch_ref=batch_ref, level=level,
                                                          refs=refs)
                if feedback is None:
                    outcome = fc.OUTCOME_MALFORMED
                    issue = "structured output failed validation: " + "; ".join(problems)
                    attempt_prompt = fc.build_retry_prompt(prompt, issue)
            elif outcome == fc.OUTCOME_MALFORMED:
                attempt_prompt = fc.build_retry_prompt(prompt, result.issue or "malformed output")
            with self.store.transaction():
                self.store.finish_claude_call(call_id, outcome=outcome, finished_at=fp.iso_utc(now))
            self.log(event="claude_call", outcome=outcome, call_number=call_number, level=level,
                     simulated=bool(getattr(self.gateway, "simulated", False)))
            if outcome != fc.OUTCOME_MALFORMED:
                break

        if outcome == fc.OUTCOME_AUTH:
            self._record_auth_result(False, now)
        elif outcome in (fc.OUTCOME_OK, fc.OUTCOME_MALFORMED):
            self._record_auth_result(True, now)  # Claude answered, so authentication works

        with self.store.transaction():
            if outcome == fc.OUTCOME_OK and feedback is not None:
                text = self._format_message(batch["kind"], level, local_date, feedback)
                self.store.set_message(batch_id, text, now_text)
                self.store.requeue_batch(batch_id, now_text, stage="deliver", level=level, generated_at=now_text,
                                         generation_attempts=batch["generation_attempts"] + 1,
                                         next_attempt_at=None, error_category=None, parts_sent=0)
                self.store.set_active_items_state(batch_id, "queued", now_text, level=level)
                self.bump(f"generated_{level}")
                return
            if outcome in fc.SYSTEMIC_OUTCOMES:
                # Not this batch's fault: no attempt spent; stop calling Claude this run.
                self.store.requeue_batch(batch_id, now_text, error_category=outcome)
                self._claude_blocked = outcome
                self.bump(f"deferred_{outcome}")
                return
            attempts = batch["generation_attempts"] + 1
            if attempts >= MAX_GENERATION_ATTEMPTS:
                self.store.update_batch(batch_id, now_text, generation_attempts=attempts)
                self.store.finish_batch(batch_id, "failed", now_text, error_category=outcome or "budget_exhausted")
                self.bump(f"failed_generation_{outcome}")
                return
            backoff = GENERATION_BACKOFF[min(attempts - 1, len(GENERATION_BACKOFF) - 1)]
            self.store.requeue_batch(batch_id, now_text, generation_attempts=attempts, error_category=outcome,
                                     next_attempt_at=fp.iso_utc(now + backoff))
            self.bump(f"retry_generation_{outcome}")

    def _format_message(self, kind: str, level: str, local_date: date, feedback: fc.Feedback) -> str:
        header = f"{LEVEL_HEADERS[(kind, level)]} — {local_date.isoformat()}"
        if feedback.safety_concern:
            header = "[ATTENTION] " + header
        return f"{header}\n\n{feedback.message}"

    def deliver(self, batch_id: int, now: datetime) -> None:
        now_text = fp.iso_utc(now)
        if self.telegram is None:
            self.bump("deferred_telegram_not_configured")
            return
        with self.store.transaction():
            if not self.store.claim_batch(batch_id, stage="deliver", owner=self.owner, now_text=now_text):
                self.bump("claim_lost")
                return
            batch = self.store.get_batch(batch_id)
            # Once a part has reached the athlete the message is completed as
            # is: regenerating would send a second, different message.
            if batch["kind"] != "system_alert" and not batch["parts_sent"]:
                valid, removed = self._revalidate_items(batch_id, now)
                if not valid:
                    self._finish_empty(batch_id, removed, now_text)
                    return
                if removed:
                    # The message mentions an event that no longer qualifies:
                    # regenerate for the remaining ones rather than send it.
                    self.store.set_message(batch_id, None, now_text)
                    self.store.requeue_batch(batch_id, now_text, stage="generate", parts_sent=0, parts_total=None,
                                             telegram_message_ids=None)
                    self.bump("regenerate_after_revalidation")
                    return
                generated = fp.parse_iso(batch["generated_at"])
                if generated is None or now - generated > DELIVERY_MAX_AGE:
                    self.store.finish_batch(batch_id, "expired", now_text, error_category="delivery_window_passed",
                                            item_reason="delivery_window_passed")
                    self.bump("batches_expired")
                    return
            text = batch["message_text"]
            if not text:
                self.store.finish_batch(batch_id, "failed", now_text, error_category="message_missing")
                self.bump("failed_message_missing")
                return
            parts = td.split_message(text)
            self.store.update_batch(batch_id, now_text, parts_total=len(parts),
                                    delivery_attempts=batch["delivery_attempts"] + 1)

        message_ids = json.loads(batch["telegram_message_ids"] or "[]")
        for index in range(batch["parts_sent"], len(parts)):
            # Committed before the request: if this process dies mid-send,
            # recovery knows a send may have reached Telegram.
            with self.store.transaction():
                self.store.update_batch(batch_id, now_text, inflight_part=index)
            outcome, retry_after, message_id = self._send(parts[index])
            if outcome != "sent":
                self._delivery_failed(batch_id, batch["delivery_attempts"] + 1, outcome, retry_after, now)
                return
            message_ids.append(message_id)
            with self.store.transaction():
                self.store.update_batch(batch_id, now_text, parts_sent=index + 1, inflight_part=None,
                                        telegram_message_ids=json.dumps(message_ids))
        with self.store.transaction():
            self.store.finish_batch(batch_id, "delivered", now_text)
        self.bump(f"delivered_{batch['kind']}")
        self.log(event="delivered", kind=batch["kind"], parts=len(parts))

    def _send(self, text: str) -> "tuple[str, Optional[int], Optional[int]]":
        """('sent' | 'retryable' | 'rejected' | 'unknown', retry_after, message_id).

        Definitive outcomes are safe to retry because Telegram cannot have
        delivered the message: an HTTP error reply (except 504, where a
        gateway timed out on a request it had forwarded), or
        TelegramNetworkError, which the transport raises only while
        connecting or sending the request (urllib wraps those in URLError).
        Anything after the request was sent -- a read timeout, a reset
        connection, an unexpected error -- is ambiguous and never retried."""
        try:
            return "sent", None, td.send_single_message(self.telegram, text, http_post=self.http_post)
        except td.TelegramAPIError as exc:
            if exc.status_code == 504:
                return "unknown", None, None
            if exc.status_code == 429 or exc.status_code >= 500:
                return "retryable", exc.retry_after, None
            return "rejected", None, None
        except td.TelegramNetworkError:
            return "retryable", None, None
        except Exception:  # noqa: BLE001 -- includes read timeouts and resets: never resend
            return "unknown", None, None

    def _delivery_failed(self, batch_id: int, attempts: int, outcome: str, retry_after: Optional[int],
                         now: datetime) -> None:
        now_text = fp.iso_utc(now)
        with self.store.transaction():
            if outcome == "rejected":
                self.store.finish_batch(batch_id, "failed", now_text, error_category="telegram_rejected",
                                        item_reason="telegram_rejected")
            elif outcome == "unknown":
                self.store.finish_batch(batch_id, "failed", now_text, error_category="delivery_outcome_unknown",
                                        item_reason="delivery_outcome_unknown")
            elif attempts >= MAX_DELIVERY_ATTEMPTS:
                self.store.finish_batch(batch_id, "failed", now_text, error_category="telegram_retries_exhausted",
                                        item_reason="telegram_retries_exhausted")
                outcome = "retries_exhausted"
            else:
                backoff = DELIVERY_BACKOFF[min(attempts - 1, len(DELIVERY_BACKOFF) - 1)]
                if retry_after is not None:
                    backoff = max(backoff, min(timedelta(seconds=retry_after), MAX_RETRY_AFTER))
                self.store.requeue_batch(batch_id, now_text, error_category="telegram_transient",
                                         next_attempt_at=fp.iso_utc(now + backoff))
        self.bump(f"delivery_{outcome}")
        self.log(event="delivery_failed", outcome=outcome, attempts=attempts)


