def migrate_check(db_path: Path, now: datetime) -> dict:
    """Migrates an in-memory copy twice (idempotency) and proves every v1 row
    survived unchanged. Reports counts only."""
    store = es.EventStore.open_snapshot(db_path)
    try:
        version = fs.schema_version(store.conn)
        before = fs.v1_snapshot(store.conn)
        result = fs.migrate_to_v2(store.conn, now_text=fp.iso_utc(now))
        again = fs.migrate_to_v2(store.conn, now_text=fp.iso_utc(now))
        after = fs.v1_snapshot(store.conn)
        return {"mode": "migrate_check", "database_modified": False, "current_version": version, **result,
                "rerun_applied": again["applied"], "v1_rows_preserved": before == after,
                "v1_row_counts": {table: len(rows) for table, rows in before.items()},
                "verification_problems": fs.verify_v2(store.conn)}
    finally:
        store.close()


def migrate_apply(db_path: Path, runtime_dir: Path, now: datetime) -> dict:
    if not db_path.exists():
        raise fs.MigrationError("event store does not exist")
    lock = wr.WorkflowLock(runtime_dir / "locks", "event-poller", ep.LOCK_STALE_SECONDS)
    lock.acquire()  # no poll may run while the store is backed up and migrated
    try:
        store = es.EventStore.open(db_path)
        try:
            if fs.schema_version(store.conn) == fs.TARGET_SCHEMA_VERSION:
                return {"mode": "migrate", **fs.migrate_to_v2(store.conn, now_text=fp.iso_utc(now)), "backup": None}
            backup_dir = runtime_dir / "backups"
            backup_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
            backup = backup_dir / f"events.v1.{now.strftime('%Y%m%dT%H%M%SZ')}.sqlite3"
            fs.backup_database(store.conn, backup)
            result = fs.migrate_to_v2(store.conn, now_text=fp.iso_utc(now))
            return {"mode": "migrate", **result, "backup": str(backup.relative_to(runtime_dir.parent))}
        finally:
            store.close()
    finally:
        lock.release()


def downgrade_apply(db_path: Path, runtime_dir: Path, now: datetime) -> dict:
    """Rollback to v1 keeping all detections: v2 backup first, then drop
    the dispatcher's tables. Holds both the poller and dispatcher locks."""
    poller_lock = wr.WorkflowLock(runtime_dir / "locks", "event-poller", ep.LOCK_STALE_SECONDS)
    dispatcher_lock = wr.WorkflowLock(runtime_dir / "locks", "feedback-dispatcher", LOCK_STALE_SECONDS)
    poller_lock.acquire()
    try:
        dispatcher_lock.acquire()
        try:
            store = es.EventStore.open(db_path)
            try:
                if fs.schema_version(store.conn) != fs.TARGET_SCHEMA_VERSION:
                    return {"mode": "downgrade", **fs.downgrade_to_v1(store.conn), "backup": None}
                backup_dir = runtime_dir / "backups"
                backup_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
                backup = backup_dir / f"events.v2.{now.strftime('%Y%m%dT%H%M%SZ')}.sqlite3"
                fs.backup_database(store.conn, backup)
                result = fs.downgrade_to_v1(store.conn)
                return {"mode": "downgrade", **result, "backup": str(backup.relative_to(runtime_dir.parent))}
            finally:
                store.close()
        finally:
            dispatcher_lock.release()
    finally:
        poller_lock.release()


def requeue_failed_deliveries(store: fs.FeedbackStore, now: datetime) -> int:
    now_text = fp.iso_utc(now)
    requeued = 0
    with store.transaction():
        for row in store.conn.execute("SELECT id FROM feedback_batches WHERE state = 'failed' AND kind != "
                                      "'system_alert'").fetchall():
            if store.requeue_failed_delivery(row["id"], now_text, RETRY_SAFE_DELIVERY_FAILURES):
                requeued += 1
    return requeued


