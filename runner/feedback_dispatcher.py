def make_logger(log_file: Optional[Path]) -> Callable[..., None]:
    def log(**fields: Any) -> None:
        safe = {k: wr.redact_secrets(v) if isinstance(v, str) else v for k, v in fields.items()}
        safe.setdefault("component", "feedback_dispatcher")
        safe.setdefault("logged_at", datetime.now(UTC).isoformat())
        line = json.dumps(safe, sort_keys=True)
        print(line, file=sys.stderr)
        if log_file:
            try:
                log_file.parent.mkdir(parents=True, exist_ok=True)
                with log_file.open("a", encoding="utf-8") as handle:
                    handle.write(line + "\n")
            except OSError:
                pass
    return log


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Event feedback dispatcher (Phase 4.3).")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--simulate", action="store_true",
                      help="run against an in-memory copy; never invokes Claude or Telegram")
    mode.add_argument("--once", action="store_true", help="live dispatch run (requires FEEDBACK_DISPATCH_ENABLED)")
    mode.add_argument("--status", action="store_true", help="print dispatch counts (read-only)")
    mode.add_argument("--migrate-check", action="store_true", help="migrate an in-memory copy to v2 and verify")
    mode.add_argument("--migrate", action="store_true", help="back up the store, then migrate it to schema v2")
    mode.add_argument("--downgrade-v1", action="store_true",
                      help="back up the store, then drop the v2 tables (rollback; keeps all detections)")
    mode.add_argument("--requeue-failed-delivery", action="store_true",
                      help="requeue feedback whose delivery Telegram definitively rejected (never ambiguous ones)")
    parser.add_argument("--expect-plan", default=None, metavar="TOKEN",
                        help="with --once: run only the approved plan printed by --simulate (supervised run)")
    parser.add_argument("--max-batches", type=int, default=None,
                        help="supervised batch limit (required with --expect-plan; also accepted by --simulate)")
    parser.add_argument("--at", default=None, help="simulation start time (ISO 8601; default now)")
    parser.add_argument("--until", default=None, help="simulation end time; steps every 15 minutes")
    parser.add_argument("--repo-root", default=None, help="override the resolved repository root")
    parser.add_argument("--env-file", default=None, help="env file (default runner/config.env)")
    parser.add_argument("--db-path", default=None, help="event store path (default runtime/events.sqlite3)")
    return parser


def argument_problem(args) -> Optional[str]:
    """Rejects ambiguous combinations instead of guessing."""
    if args.expect_plan is not None and not args.once:
        return "--expect-plan is only valid with --once"
    if args.once and args.expect_plan is not None and args.max_batches is None:
        return "--expect-plan requires --max-batches"
    if args.max_batches is not None:
        if not (args.simulate or (args.once and args.expect_plan is not None)):
            return "--max-batches is only valid with --simulate or with --once --expect-plan"
        if not 1 <= args.max_batches <= MAX_SUPERVISED_BATCHES:
            return f"--max-batches must be between 1 and {MAX_SUPERVISED_BATCHES}"
        if args.simulate and args.until is not None:
            return "--max-batches simulates a single supervised run; --until is not supported with it"
    if (args.at is not None or args.until is not None) and not args.simulate:
        return "--at and --until are only valid with --simulate"
    return None


def settings_from_env(env: dict, repo_root: Path, tz: ZoneInfo) -> Settings:
    budget = env.get("FEEDBACK_DAILY_CLAUDE_BUDGET", "").strip()
    return Settings(
        repo_root=repo_root, tz=tz,
        daily_budget=int(budget) if budget else DEFAULT_DAILY_CLAUDE_BUDGET,
        apple_health_verified=ep.APPLE_HEALTH_STRUCTURE_VERIFIED,
        claude_binary=env.get("CLAUDE_BINARY", "").strip() or wr.DEFAULT_CLAUDE_BINARY,
        auth_expires_on=fc.parse_expiry_date(env.get("CLAUDE_AUTH_EXPIRES_ON")),
    )


def _parse_cli_time(value: Optional[str], default: datetime) -> datetime:
    parsed = fp.parse_iso(value) if value else default
    if parsed is None:
        raise ValueError("invalid time")
    return parsed.astimezone(UTC)


def main(argv: Optional[list] = None, *, now_fn: Optional[Callable[[], datetime]] = None,
         gateway_factory: Optional[Callable] = None, http_post: Optional[Callable] = None) -> int:
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    problem = argument_problem(args)
    if problem:
        print(json.dumps({"outcome": "failed", "error_category": "invalid_arguments", "error": problem}))
        return 2
    repo_root = Path(args.repo_root).resolve() if args.repo_root else wr.default_repo_root()
    env = wr.load_env_file(Path(args.env_file) if args.env_file else repo_root / "runner" / "config.env")
    env.update(os.environ)
    now = (now_fn or (lambda: datetime.now(UTC)))()

    def fail(category: str, code: int, **extra: Any) -> int:
        print(json.dumps({"outcome": "failed", "error_category": category, **extra}, sort_keys=True))
        return code

    try:
        tz = ZoneInfo(env.get("ATHLETE_TIMEZONE", "").strip())
        settings = settings_from_env(env, repo_root, tz)
    except Exception:  # noqa: BLE001
        return fail("config_error", 2)
    # Simulation writes nothing to disk, not even a log file.
    log_file_value = "" if args.simulate else env.get("FEEDBACK_LOG_FILE", "").strip()
    log = make_logger(Path(log_file_value) if log_file_value else None)

    runtime_dir = repo_root / "runtime"
    db_path = Path(args.db_path) if args.db_path else runtime_dir / "events.sqlite3"

    if args.status:
        if not db_path.exists():
            print(json.dumps({"status": "no_database"}))
            return 0
        store = es.EventStore.open_readonly(db_path)
        try:
            if fs.schema_version(store.conn) != fs.TARGET_SCHEMA_VERSION:
                print(json.dumps({"schema_version": fs.schema_version(store.conn), "status": "not_migrated"}))
                return 0
            fstore = fs.FeedbackStore(store)
            print(json.dumps(fstore.status_summary(now.astimezone(tz).date().isoformat()), indent=2,
                             sort_keys=True))
        finally:
            store.close()
        return 0

    if args.migrate_check:
        try:
            print(json.dumps(migrate_check(db_path, now), indent=2, sort_keys=True))
        except (es.StoreError, sqlite3.Error) as exc:
            return fail(getattr(exc, "category", "store_error"), 1)
        return 0

    if args.migrate:
        try:
            print(json.dumps(migrate_apply(db_path, runtime_dir, now), indent=2, sort_keys=True))
        except wr.DuplicateExecutionError:
            return fail("poller_running", 1)
        except (es.StoreError, sqlite3.Error, OSError) as exc:
            return fail(getattr(exc, "category", "store_error"), 1)
        return 0

    if args.downgrade_v1:
        try:
            print(json.dumps(downgrade_apply(db_path, runtime_dir, now), indent=2, sort_keys=True))
        except wr.DuplicateExecutionError:
            return fail("lock_held", 1)
        except (es.StoreError, sqlite3.Error, OSError) as exc:
            return fail(getattr(exc, "category", "store_error"), 1)
        return 0

    if args.simulate:
        if not db_path.exists():
            return fail("no_database", 1)
        try:
            start = _parse_cli_time(args.at, now)
            until = _parse_cli_time(args.until, start) if args.until else None
            summary = simulate(db_path, settings, start=start, until=until, log=log, max_batches=args.max_batches,
                               live_clock=args.at is None)
        except ValueError as exc:
            return fail("invalid_arguments", 2, error=str(exc))
        except (es.StoreError, sqlite3.Error) as exc:
            return fail(getattr(exc, "category", "store_error"), 1)
        print(json.dumps(summary, indent=2, sort_keys=True))
        return 0

    if args.requeue_failed_delivery:
        lock = wr.WorkflowLock(runtime_dir / "locks", "feedback-dispatcher", LOCK_STALE_SECONDS)
        try:
            lock.acquire()
        except wr.DuplicateExecutionError:
            return fail("lock_held", 1)
        try:
            base = es.EventStore.open(db_path)
            try:
                count = requeue_failed_deliveries(fs.FeedbackStore(base), now)
            finally:
                base.close()
        except (es.StoreError, sqlite3.Error) as exc:
            return fail(getattr(exc, "category", "store_error"), 1)
        finally:
            lock.release()
        print(json.dumps({"outcome": "ok", "requeued": count}))
        return 0

    # --once (live)
    if env.get("FEEDBACK_DISPATCH_ENABLED", "").strip().lower() != "true":
        # Exit 0 so a timer installed before enablement stays quiet.
        log(event="dispatch_skipped", reason="disabled")
        print(json.dumps({"outcome": "skipped", "reason": "dispatch_disabled"}))
        return 0
    if not db_path.exists():
        return fail("no_database", 1)
    lock = wr.WorkflowLock(runtime_dir / "locks", "feedback-dispatcher", LOCK_STALE_SECONDS)
    try:
        lock.acquire()
    except wr.DuplicateExecutionError:
        log(event="dispatch_skipped", reason="lock_held")
        return 0
    try:
        base = None
        try:
            base = es.EventStore.open(db_path)
            store = fs.FeedbackStore(base)
        except (es.StoreError, sqlite3.Error) as exc:
            if base is not None:
                base.close()
            return fail(getattr(exc, "category", "store_error"), 1)
        try:
            config = wr.RunnerConfig.from_env(env, repo_root_override=str(repo_root))
            gateway = gateway_factory(config) if gateway_factory else fc.ClaudeGateway(config)
            telegram = td.load_telegram_config(env)
            dispatcher = Dispatcher(store, settings, gateway=gateway, telegram=telegram, http_post=http_post, log=log)
            started = fp.iso_utc(now)
            if args.expect_plan:
                result = dispatcher.run_supervised(now, args.expect_plan, args.max_batches)
                if result["outcome"] != "ok":
                    # Rejected before any change: nothing written, no Claude, no Telegram.
                    log(event="supervised_rejected", outcome=result["outcome"])
                    print(json.dumps(result, indent=2, sort_keys=True))
                    return 3
                with store.transaction():
                    store.record_dispatch_run(started_at=started, finished_at=fp.iso_utc(datetime.now(UTC)),
                                              mode="supervised", outcome="ok", summary=result["counts"])
                log(event="dispatch_end", outcome="ok", mode="supervised", counts=result["counts"])
                print(json.dumps(result, indent=2, sort_keys=True))
                return 0
            dispatcher.activate(now)
            counts = dispatcher.run(now)
            with store.transaction():
                store.record_dispatch_run(started_at=started, finished_at=fp.iso_utc(datetime.now(UTC)),
                                          mode="once", outcome="ok", summary=counts)
            log(event="dispatch_end", outcome="ok", **{"counts": counts})
            print(json.dumps({"outcome": "ok", "counts": counts}, indent=2, sort_keys=True))
            return 0
        except wr.ConfigError:
            return fail("config_error", 2)
        finally:
            store.store.close()
    finally:
        lock.release()


if __name__ == "__main__":
    sys.exit(main())
