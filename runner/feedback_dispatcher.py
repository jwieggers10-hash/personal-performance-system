class RecordingTransport:
    """--simulate and tests: records sendMessage calls; never touches the network."""

    def __init__(self):
        self.messages: list = []

    def __call__(self, url: str, data: dict, timeout: float = 10.0):
        self.messages.append(data["text"])
        return 200, json.dumps({"ok": True, "result": {"message_id": len(self.messages)}})


